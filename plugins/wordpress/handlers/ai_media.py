OG_SIZE = (1200, 630)


def make_og_variant(data: bytes, size: tuple[int, int] = OG_SIZE) -> bytes:
    """Return a centre-cropped JPEG of ``size`` (Open Graph 1.91:1) from image bytes.

    Transparent images are flattened onto white (JPEG has no alpha).
    """
    import io

    from PIL import Image, ImageOps

    with Image.open(io.BytesIO(data)) as src:
        img = ImageOps.exif_transpose(src)
        if img.mode in ("RGBA", "LA", "P"):
            rgba = img.convert("RGBA")
            flat = Image.new("RGB", rgba.size, (255, 255, 255))
            flat.paste(rgba, mask=rgba.split()[-1])
            img = flat
        else:
            img = img.convert("RGB")
        fitted = ImageOps.fit(img, size, method=Image.Resampling.LANCZOS, centering=(0.5, 0.5))
        buf = io.BytesIO()
        fitted.save(buf, "JPEG", quality=88, optimize=True, progressive=True)
        return buf.getvalue()


class AIMediaHandler:
    """Handles AI-powered image generation + WP upload chain."""

    def __init__(
        self,
        client: WordPressClient,
        user_id: str | None = None,
        site_id: str | None = None,
        wc_client: WordPressClient | None = None,
    ):
        self.client = client
        # ``user_id`` is injected by the user-endpoint plumbing (F.5a.4).
        # Admin / system endpoints leave it None.
        self.user_id = user_id
        # ``site_id`` is injected by the user-endpoint plumbing (F.5a.9.x)
        # and is the primary input for resolving per-site provider API
        # keys. Admin / env-driven endpoints leave it None, in which case
        # the resolver falls back to the legacy env-var path.
        self.site_id = site_id
        # F.X.fix-pass6 — optional separate client for /wc/v3/* (the
        # WC consumer-key/secret pair on a WC site). Used by
        # _apply_metadata_and_attach to detect "attach_to_post is a
        # WC product" and route the featured-image set through
        # /wc/v3/products/{id}/images instead of /wp/v2/posts/{id}
        # which 404s for the product CPT. None = same client serves
        # both REST roots (WP plugin or legacy single-credential WC).
        self.wc_client = wc_client

    async def generate_and_upload_image(
        self,
        provider: str,
        prompt: str,
        size: str = "1024x1024",
        quality: str = "standard",
        model: str | None = None,
        negative_prompt: str | None = None,
        input_images_b64: list[str] | None = None,
        filename: str | None = None,
        title: str | None = None,
        alt_text: str | None = None,
        caption: str | None = None,
        attach_to_post: int | None = None,
        set_featured: bool = False,
        skip_optimize: bool = False,
        convert_to: str | None = None,
        connection_id: str | None = None,
        generate_og_variant: bool = False,
    ) -> str:
        started = time.time()
        try:
            from core.tool_rate_limiter import ToolRateLimitError, get_tool_rate_limiter

            try:
                get_tool_rate_limiter().check("wordpress_generate_and_upload_image", self.user_id)
            except ToolRateLimitError as e:
                return json.dumps(e.to_dict(), indent=2)

            provider_impl = get_provider(provider)
            provider_extras: dict[str, Any] = {}
            if provider == "openai_compatible":
                if not self.site_id or not connection_id:
                    return json.dumps(
                        {
                            "error_code": "NO_PROVIDER_CONFIG",
                            "message": "Select a compatible provider connection.",
                        },
                        indent=2,
                    )
                secret = await get_site_ai_provider_secret(self.site_id, connection_id)
                if secret is None:
                    return json.dumps(
                        {
                            "error_code": "NO_PROVIDER_CONFIG",
                            "message": "Compatible provider connection not found.",
                        },
                        indent=2,
                    )
                row, api_key = secret
                provider_extras = {
                    "base_url": row["base_url"],
                    "api_type": row["api_type"],
                    "model_id": row.get("model_id"),
                    "connection_id": connection_id,
                }
            else:
                api_key = await self._resolve_api_key(provider)
            # F.X.fix-pass3 — when caller omitted ``model``, fall back
            # to the per-site default the operator pinned in the
            # dashboard. Keeps MCP call sites short and lets the user
            # rotate models without code changes.
            if model is None and self.site_id:
                try:
                    from core.database import get_database

                    db = get_database()
                    model = await db.get_site_provider_default_model(self.site_id, provider)
                except Exception as exc:  # noqa: BLE001
                    _logger.debug(
                        "default_model lookup skipped site=%s provider=%s: %s",
                        self.site_id,
                        provider,
                        exc,
                    )
            if not api_key:
                if self.site_id:
                    msg = (
                        f"No API key configured for provider '{provider}' on "
                        f"this site. Open the site in the dashboard and add the "
                        f"key under 'AI Image Generation' in Connection Settings."
                    )
                    dashboard_url = f"/dashboard/sites/{self.site_id}"
                else:
                    msg = (
                        f"No API key configured for provider '{provider}'. "
                        f"Set the {provider.upper()}_API_KEY env var on the server."
                    )
                    dashboard_url = None
                payload = {
                    "error_code": "NO_PROVIDER_KEY",
                    "message": msg,
                    "provider": provider,
                }
                if dashboard_url:
                    payload["dashboard_url"] = dashboard_url
                return json.dumps(payload, indent=2)

            input_images: list[bytes] = []
            input_image_mimes: list[str] = []
            for encoded in input_images_b64 or []:
                try:
                    header, value = (
                        encoded.split(",", 1) if encoded.startswith("data:") else ("", encoded)
                    )
                    input_images.append(base64.b64decode(value, validate=True))
                    input_image_mimes.append(
                        header.split(";", 1)[0].removeprefix("data:") or "image/png"
                    )
                except (ValueError, base64.binascii.Error) as exc:
                    raise UploadError("BAD_BASE64", f"Invalid input image base64: {exc}") from exc

            if model is None and provider_extras.get("model_id"):
                model = provider_extras["model_id"]
            request = GenerationRequest(
                prompt=prompt,
                size=size,
                quality=quality,
                model=model,
                negative_prompt=negative_prompt,
                input_images=input_images,
                input_image_mimes=input_image_mimes,
                extras=provider_extras,
            )
            result = await provider_impl.generate(api_key, request)

            data, mime_hint = _maybe_optimize(
                result.data, result.mime, skip=skip_optimize, convert_to=convert_to
            )
            # F.X.fix #7: stable idempotency key per logical call. A
            # client-side retry (after timeout) produces the same
            # digest, so the companion dedupes instead of creating an
            # "-2.webp" orphan. Key covers every input that would
            # change the intended outcome.
            idempotency_key = _idempotency_key_for(
                provider=provider,
                model=result.meta.get("model") or model,
                prompt=prompt,
                size=size,
                attach_to_post=attach_to_post,
                set_featured=set_featured,
                site_url=self.client.site_url,
                user_id=self.user_id,
                content_sha=_content_sha(data),
            )
            media = await wp_raw_upload(
                self.client,
                data,
                filename=filename or result.filename,
                mime_hint=mime_hint or result.mime,
                # F.5a.8.5: single-call upload+metadata+attach+featured
                # when the companion's upload-and-attach route is
                # advertised; _apply_metadata_and_attach becomes a no-op.
                attach_to_post=attach_to_post,
                set_featured=set_featured,
                title=title,
                alt_text=alt_text,
                caption=caption,
                idempotency_key=idempotency_key,
            )
            attach_status = await _apply_metadata_and_attach(
                self.client,
                media,
                title=title,
                alt_text=alt_text,
                caption=caption,
                attach_to_post=attach_to_post,
                set_featured=set_featured,
                wc_client=self.wc_client,
            )

            duration_ms = int((time.time() - started) * 1000)
            self._audit(
                provider=provider,
                model=result.meta.get("model") or model,
                size=size,
                duration_ms=duration_ms,
                bytes_=len(result.data),
                cost_usd=result.cost_usd,
                media_id=media.get("id"),
                error=None,
            )
            from core.media_audit import log_media_upload

            log_media_upload(
                site=self.client.site_url,
                user_id=self.user_id,
                mime=media.get("mime_type") or result.mime,
                size_bytes=len(data),
                source=f"ai:{provider}",
                media_id=media.get("id"),
                cost_usd=result.cost_usd,
            )

            # F.X.fix-pass6 — surface partial-success: media uploaded
            # but featured-set / metadata-apply may have warnings. Old
            # behaviour bubbled those exceptions up as
            # GENERATION_FAILED, hiding the freshly-created media id
            # and leaving an orphan in the library.
            payload = _format_upload_result(media, source=f"ai:{provider}")
            payload["provider"] = provider
            payload["provider_meta"] = result.meta
            payload["cost_usd"] = result.cost_usd
            payload["duration_ms"] = duration_ms
            payload["attach"] = {
                "metadata_applied": attach_status.get("metadata_applied", False),
                "featured_set": attach_status.get("featured_set", False),
                "featured_context": attach_status.get("featured_context"),
            }
            warnings = list(attach_status.get("warnings") or [])
            if generate_og_variant:
                payload["og_variant"] = await self._upload_og_variant(
                    data,
                    base_filename=filename or result.filename,
                    title=title,
                    alt_text=alt_text,
                    attach_to_post=attach_to_post,
                    idempotency_key=f"{idempotency_key}:og",
                    warnings=warnings,
                )
            if warnings:
                payload["warnings"] = warnings
            return json.dumps(payload, indent=2)

        except ProviderError as e:
            self._audit(
                provider=provider,
                model=model,
                size=size,
                duration_ms=int((time.time() - started) * 1000),
                bytes_=0,
                cost_usd=None,
                media_id=None,
                error=e.code,
            )
            return json.dumps(e.to_dict(), indent=2)
        except UploadError as e:
            self._audit(
                provider=provider,
                model=model,
                size=size,
                duration_ms=int((time.time() - started) * 1000),
                bytes_=0,
                cost_usd=None,
                media_id=None,
                error=e.code,
            )
            return json.dumps(e.to_dict(), indent=2)
        except Exception as e:
            _logger.exception("generate_and_upload_image failed")
            return json.dumps(
                {
                    "error_code": "GENERATION_FAILED",
                    "message": f"generate_and_upload_image failed: {e}",
                },
                indent=2,
            )

    async def _resolve_api_key(self, provider: str) -> str | None:
        """Resolve the provider key for this call.

        F.5a.9.x policy (single-source, per-site):

        1. ``site_id`` set (per-user endpoint, the only UI-reachable path):
           read the key from the per-site ``site_provider_keys`` row.
           Env fallback is deliberately NOT applied here so a single
           ``OPENAI_API_KEY=...`` on the server cannot silently paper
           over a missing per-site configuration — callers instead get
           ``NO_PROVIDER_KEY`` pointing at the site's dashboard page.

        2. ``site_id is None`` (admin / master-key endpoint, no site
           context): fall back to the ``<PROVIDER>_API_KEY`` env var.
           This preserves the legacy self-hosted / admin workflow.

        The per-user provider-keys store from F.18.8 has been removed
        in favour of the per-site model; there is no hybrid fallback.
        """
        # 1. Per-site key (the primary path)
        if self.site_id:
            try:
                from core.site_api import get_site_provider_key

                return await get_site_provider_key(self.site_id, provider)
            except Exception as exc:
                _logger.error(
                    "Site provider-key lookup failed site=%s provider=%s: %s",
                    self.site_id,
                    provider,
                    exc,
                )
                return None

        # 2. Admin / env-var fallback (no site context)
        env_var = f"{provider.upper()}_API_KEY"
        return os.environ.get(env_var)

    async def _upload_og_variant(
        self,
        data: bytes,
        *,
        base_filename: str | None,
        title: str | None,
        alt_text: str | None,
        attach_to_post: int | None,
        idempotency_key: str,
        warnings: list[str],
    ) -> dict[str, Any]:
        """Upload a 1200x630 Open Graph crop and point Rank Math at it (#93).

        Social cards want ~1.91:1; AI covers are often square, so Rank Math
        correctly reported og:image 1024x1024 for a square cover. The crop is
        a separate attachment; the original stays the featured/hero image.
        Failures are reported as warnings — the main upload already succeeded.
        """
        out: dict[str, Any] = {"width": OG_SIZE[0], "height": OG_SIZE[1]}
        try:
            og_bytes = make_og_variant(data)
        except Exception as exc:  # noqa: BLE001
            warnings.append(f"OG variant not created: {exc}")
            out["error"] = str(exc)
            return out
        stem = (base_filename or "image").rsplit(".", 1)[0]
        media = await wp_raw_upload(
            self.client,
            og_bytes,
            filename=f"{stem}-og-1200x630.jpg",
            mime_hint="image/jpeg",
            title=f"{title} (Open Graph)" if title else None,
            alt_text=alt_text,
            idempotency_key=idempotency_key,
        )
        out.update(media_id=media.get("id"), source_url=media.get("source_url"))
        out["rank_math_og_set"] = False
        if attach_to_post and media.get("id"):
            out["rank_math_og_set"] = await self._set_rank_math_og_image(
                attach_to_post, media["id"], media.get("source_url") or "", warnings
            )
        return out

    async def _set_rank_math_og_image(
        self, post_id: int, media_id: int, url: str, warnings: list[str]
    ) -> bool:
        """Set Rank Math's Facebook image meta on a post or page.

        WordPress silently ignores unregistered meta keys, so success is read
        back from the response (the companion registers Rank Math meta).
        """
        meta = {"rank_math_facebook_image": url, "rank_math_facebook_image_id": int(media_id)}
        for endpoint in (f"posts/{post_id}", f"pages/{post_id}"):
            try:
                resp = await self.client.post(endpoint, json_data={"meta": meta})
            except Exception as exc:  # noqa: BLE001
                if "NOT_FOUND" in str(exc) or "rest_post_invalid_id" in str(exc):
                    continue
                warnings.append(f"Rank Math OG image not set: {exc}")
                return False
            saved = (resp or {}).get("meta") or {}
            if str(saved.get("rank_math_facebook_image_id")) == str(media_id):
                return True
            warnings.append(
                "Rank Math OG image meta was not saved (Rank Math inactive or the "
                "Airano MCP Bridge companion that registers its meta is missing)."
            )
            return False
        warnings.append(f"Rank Math OG image not set: post {post_id} is not a post or page")
        return False

    def _audit(
        self,
        *,
        provider: str,
        model: str | None,
        size: str,
        duration_ms: int,
        bytes_: int,
        cost_usd: float | None,
        media_id: int | None,
        error: str | None,
    ) -> None:
        try:
            from core.audit_log import get_audit_logger

            logger_ = get_audit_logger()
        except Exception:
            return
        try:
            logger_.log_tool_call(
                tool_name="wordpress_generate_and_upload_image",
                params={
                    "provider": provider,
                    "model": model,
                    "size": size,
                    "bytes": bytes_,
                    "cost_usd": cost_usd,
                    "media_id": media_id,
                },
                duration_ms=duration_ms,
                user_id=self.user_id,
                error=error,
                result_summary=(
                    f"{provider}/{model or '-'} {bytes_}B "
                    f"${cost_usd or 0:.4f} -> media_id={media_id}"
                    if not error
                    else f"failed: {error}"
                ),
            )
        except Exception:
            _logger.debug("audit log emit failed", exc_info=True)
